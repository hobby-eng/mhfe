// Audit AUD-024 at commit b6fca69: does the repository's tooling keep TOOL-01 (Node by default;
// Python only for independent reimplementations or a library only Python has; shell a thin
// wrapper)? Three checks, each printed with PASS or FAIL; the exit code is 1 when any fails.
//
//  1. generator-imports: scripts/generate-published-rounds.py imports only modules that Node.js's
//     standard library also covers (json, sys, pathlib) and names no Python-only library.
//     FAIL means the generator has no reason TOOL-01 accepts for Python.
//  2. node-port: the generator's job, written here with Node.js's standard library alone, gives
//     src/mhfe/published_rounds.rs byte for byte. FAIL here would mean the port is wrong; PASS
//     shows that nothing only Python has is needed.
//  3. shell-python: no tracked shell script outside docs/audits carries a Python program
//     (a heredoc fed to python3, or a multi-line python3 -c). FAIL lists each with its lines.
//
//   node docs/audits/AUD-024-harnesses/verify-tool01-python/check-tool01.mjs

import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, readdirSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(fileURLToPath(new URL("../../../..", import.meta.url)));
const results = [];
const report = (name, passed, detail) => {
  results.push(passed);
  console.log(`${passed ? "PASS" : "FAIL"} ${name}: ${detail}`);
};

// 1. The generator's imports (after a port to .mjs the Python file is gone and the check passes).
const generatorPath = join(root, "scripts/generate-published-rounds.py");
const generator = existsSync(generatorPath) ? readFileSync(generatorPath, "utf8") : null;
if (generator === null) {
  report("generator-imports", true, "scripts/generate-published-rounds.py no longer exists");
}
const imports = (generator ?? "")
  .split("\n")
  .map((line, index) => [index + 1, line])
  .filter(([, line]) => /^(?:import|from) /u.test(line));
const modules = imports.map(([, line]) => line.split(/\s+/u)[1].split(".")[0]);
const nodeCovered = new Set(["json", "sys", "pathlib"]);
const pythonOnly = modules.filter((name) => !nodeCovered.has(name));
const mentionsUnicodedata = /unicodedata/u.test(generator ?? "");
const saysComputesNothing = /it computes nothing/u.test(generator ?? "");
if (generator !== null) report(
  "generator-imports",
  pythonOnly.length > 0 || mentionsUnicodedata,
  `scripts/generate-published-rounds.py imports ${imports
    .map(([number, line]) => `${line.trim()} (:${number})`)
    .join(", ")}; modules outside json/sys/pathlib: ${pythonOnly.length ? pythonOnly.join(", ") : "none"}; ` +
    `names unicodedata: ${mentionsUnicodedata}; docstring says "it computes nothing": ${saysComputesNothing}`,
);

// 2. The same job with Node.js's standard library.
const SUITES = [
  ["suite3-vectors", false],
  ["suite4-vectors", true],
];
const STARTUP = [
  "zero-12",
  "nonzero-15",
  "zero-24",
  "ambiguous-12-21",
  "unicode-password",
  "zero-12-pim-1-memory-level-1",
  "same-length-zero-12",
  "same-length-unicode-password",
  "same-length-zero-18",
  "same-length-nonzero-21",
];
const rustText = (text) => {
  let out = "";
  for (const character of text) {
    const code = character.codePointAt(0);
    if (character === '"' || character === "\\") out += `\\${character}`;
    else if (code >= 0x20 && code <= 0x7e) out += character;
    else out += `\\u{${code.toString(16)}}`;
  }
  return `"${out}"`;
};
const rustBytes = (hex) => {
  let out = "";
  for (const byte of Buffer.from(hex, "hex")) {
    const character = String.fromCharCode(byte);
    if (character === '"' || character === "\\") out += `\\${character}`;
    else if (byte >= 0x20 && byte <= 0x7e) out += character;
    else out += `\\x${byte.toString(16).padStart(2, "0")}`;
  }
  return `b"${out}"`;
};
const published = [];
for (const [folder, sameLength] of SUITES) {
  const directory = join(root, "tests/fixtures", folder);
  for (const name of readdirSync(directory).filter((file) => file.endsWith(".json")).sort()) {
    const vector = JSON.parse(readFileSync(join(directory, name), "utf8"));
    if (vector === null || typeof vector !== "object" || Array.isArray(vector)) continue;
    if (!("inputs" in vector)) continue;
    published.push([vector, sameLength]);
  }
}
const lines = [
  "//! The published MHFE vectors as the self-checks replay them: inputs, container, recovery and",
  "//! the salt and Argon2id key of every round. Generated by scripts/generate-published-rounds.py",
  "//! from tests/fixtures/suite3-vectors and tests/fixtures/suite4-vectors (the specification's",
  "//! vectors/suite3 and vectors/suite4); do not edit. The unit test",
  "//! published_round_table_equals_the_fixtures compares every value with the fixtures.",
  "",
  "use super::known_answers::{PublishedReading, PublishedRound, PublishedVector};",
  "use crate::self_check::hex;",
  "",
  `pub(super) static PUBLISHED: [PublishedVector; ${published.length}] = [`,
];
for (const [vector, sameLength] of published) {
  const { inputs } = vector;
  lines.push(
    "    PublishedVector {",
    `        name: ${rustText(vector.name)},`,
    `        same_length: ${sameLength},`,
    `        startup: ${STARTUP.includes(vector.name)},`,
    `        phrase: ${rustText(inputs.phrase)},`,
    `        password: ${rustText(inputs.password)},`,
    `        password_nfkd: ${rustBytes(inputs.password_nfkd_utf8_hex)},`,
    `        pim: ${inputs.pim},`,
    `        memory_level: ${inputs.memory_level},`,
    `        container: ${rustText(vector.container)},`,
    "        recovery: &[",
  );
  const recovery = sameLength ? [vector.recovery] : vector.recovery;
  for (const reading of recovery) {
    lines.push(
      "            PublishedReading {",
      `                words: ${reading.words},`,
      `                verified: ${reading.verified ? "true" : "false"},`,
      `                phrase: ${rustText(reading.phrase)},`,
      "            },",
    );
  }
  lines.push("        ],", "        rounds: [");
  for (const round of vector.encryption.rounds) {
    lines.push(
      "            PublishedRound {",
      `                salt: hex("${round.salt_hex}"),`,
      `                key: hex("${round.argon2_key_hex}"),`,
      "            },",
    );
  }
  lines.push("        ],", "    },");
}
lines.push("];", "");
const rendered = lines.join("\n");
// The remediation changes only the generator's filename in the header. Retain the independent
// renderer and compare every other byte, rather than regenerating expectations from the new code.
const committed = readFileSync(join(root, "src/mhfe/published_rounds.rs"), "utf8")
  .replace("scripts/generate-published-rounds.mjs", "scripts/generate-published-rounds.py");
report(
  "node-port",
  rendered === committed,
  `a Node.js standard-library port (node:fs, node:path, JSON.parse, Buffer) renders ${published.length} vectors, ` +
    `${Buffer.byteLength(rendered)} bytes; committed src/mhfe/published_rounds.rs has ${Buffer.byteLength(committed)} bytes; ` +
    `identical apart from the generator header: ${rendered === committed}`,
);

// 3. Python programs inside tracked shell scripts.
const shellFiles = execFileSync("git", ["ls-files", "*.sh"], { cwd: root, encoding: "utf8" })
  .split("\n")
  .filter((path) => path && !path.startsWith("docs/audits/"));
const embedded = [];
for (const path of shellFiles) {
  const text = readFileSync(join(root, path), "utf8").split("\n");
  for (let index = 0; index < text.length; index += 1) {
    const line = text[index];
    const heredoc = /python3?\b.*<<-?'?(\w+)'?/u.exec(line);
    if (heredoc) {
      const end = text.findIndex((other, at) => at > index && other.trim() === heredoc[1]);
      embedded.push(`${path}:${index + 1}-${end + 1} heredoc, ${end - index - 1} lines of Python`);
      continue;
    }
    const inline = /python3?\s+-c\s+'([^']*)$/u.exec(line);
    if (inline) {
      const end = text.findIndex((other, at) => at > index && other.includes("'"));
      embedded.push(`${path}:${index + 1}-${end + 1} python3 -c, ${end - index} lines of Python`);
    }
  }
}
report(
  "shell-python",
  embedded.length === 0,
  embedded.length ? `\n  ${embedded.join("\n  ")}` : "no shell script carries a Python program",
);

process.exit(results.every(Boolean) ? 0 : 1);
