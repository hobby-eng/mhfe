// Copies published fixture values into the self-check table; performs no cryptographic work.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

import { scriptArguments } from "./gate-command-line.mjs";

const { values } = scriptArguments("usage: node scripts/generate-published-rounds.mjs [--check]", {
  options: { check: { type: "boolean" } },
});
const ROOT = new URL("../", import.meta.url);
const OUTPUT = new URL("src/mhfe/published_rounds.rs", ROOT);
const SUITES = [
  ["suite3-vectors", false],
  ["suite4-vectors", true],
];
// The selected packing, settings, password, repair and ambiguous-reading startup vectors.
const STARTUP = new Set([
  "zero-12",
  "nonzero-15",
  "zero-24",
  "ambiguous-12-21",
  "unicode-password",
  "zero-12-pim-1-memory-level-1",
  "same-length-zero-12",
  "same-length-unicode-password",
  "same-length-zero-18",
  "same-length-nonzero-21",
]);
const ROUNDS = 12; // Published format: suite 3 and suite 4 each contain twelve cipher rounds.

/** An ASCII Rust string literal, escaping every non-ASCII scalar by its code point. */
function rustText(text) {
  return (
    '"' +
    [...text]
      .map((character) => {
        if ('"\\'.includes(character)) return "\\" + character;
        if (character >= " " && character <= "~") return character;
        return `\\u{${character.codePointAt(0).toString(16)}}`;
      })
      .join("") +
    '"'
  );
}

/** The exact NFKD bytes from the fixture, with readable ASCII preserved in a byte literal. */
function rustBytes(hex) {
  if (!/^(?:[a-f\d]{2})*$/iu.test(hex)) throw new Error("Invalid fixture byte string.");
  return (
    'b"' +
    [...Buffer.from(hex, "hex")]
      .map((byte) => {
        const character = String.fromCharCode(byte);
        if ('"\\'.includes(character)) return "\\" + character;
        return byte >= 0x20 && byte <= 0x7e
          ? character
          : `\\x${byte.toString(16).padStart(2, "0")}`;
      })
      .join("") +
    '"'
  );
}

/** Every vector, ordered by filename within its suite, excluding non-vector JSON records. */
function vectors() {
  return SUITES.flatMap(([name, sameLength]) => {
    const folder = new URL(`tests/fixtures/${name}/`, ROOT);
    return readdirSync(folder)
      .filter((file) => file.endsWith(".json"))
      .sort()
      .flatMap((file) => {
        const vector = JSON.parse(readFileSync(new URL(file, folder), "utf8"));
        return vector !== null &&
          typeof vector === "object" &&
          !Array.isArray(vector) &&
          "inputs" in vector
          ? [{ vector, sameLength }]
          : [];
      });
  });
}

/** Renders exactly the inputs and published round answers used by the Rust self-checks. */
function render() {
  const published = vectors();
  const names = new Set(published.map(({ vector }) => vector.name));
  const missing = [...STARTUP].filter((name) => !names.has(name));
  if (missing.length) throw new Error(`Startup vectors not found: ${missing.join(", ")}`);
  const lines = [
    "//! The published MHFE vectors as the self-checks replay them: inputs, container, recovery and",
    "//! the salt and Argon2id key of every round. Generated by scripts/generate-published-rounds.mjs",
    "//! from tests/fixtures/suite3-vectors and tests/fixtures/suite4-vectors (the specification's",
    "//! vectors/suite3 and vectors/suite4); do not edit. The unit test",
    "//! published_round_table_equals_the_fixtures compares every value with the fixtures.",
    "",
    "use super::known_answers::{PublishedReading, PublishedRound, PublishedVector};",
    "use crate::self_check::hex;",
    "",
    `pub(super) static PUBLISHED: [PublishedVector; ${published.length}] = [`,
  ];
  for (const { vector, sameLength } of published) {
    const inputs = vector.inputs;
    lines.push(
      "    PublishedVector {",
      `        name: ${rustText(vector.name)},`,
      `        same_length: ${sameLength},`,
      `        startup: ${STARTUP.has(vector.name)},`,
      `        phrase: ${rustText(inputs.phrase)},`,
      `        password: ${rustText(inputs.password)},`,
      `        password_nfkd: ${rustBytes(inputs.password_nfkd_utf8_hex)},`,
      `        pim: ${inputs.pim},`,
      `        memory_level: ${inputs.memory_level},`,
      `        container: ${rustText(vector.container)},`,
      "        recovery: &[",
    );
    const readings = sameLength ? [vector.recovery] : vector.recovery;
    for (const { words, verified, phrase } of readings) {
      lines.push(
        "            PublishedReading {",
        `                words: ${words},`,
        `                verified: ${verified},`,
        `                phrase: ${rustText(phrase)},`,
        "            },",
      );
    }
    lines.push("        ],", "        rounds: [");
    if (vector.encryption.rounds.length !== ROUNDS) {
      throw new Error(`${vector.name}: ${vector.encryption.rounds.length} rounds`);
    }
    for (const round of vector.encryption.rounds) {
      lines.push(
        "            PublishedRound {",
        `                salt: hex("${round.salt_hex}"),`,
        `                key: hex("${round.argon2_key_hex}"),`,
        "            },",
      );
    }
    lines.push("        ],", "    },");
  }
  return [...lines, "];", ""].join("\n");
}

const text = render();
if (values.check) {
  if (readFileSync(OUTPUT, "utf8") !== text) {
    console.error("src/mhfe/published_rounds.rs differs from the fixtures; regenerate it.");
    process.exitCode = 1;
  }
} else {
  writeFileSync(OUTPUT, text);
}
