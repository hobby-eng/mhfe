//! `cargo xtask published-rounds [--check]`: writes `src/mhfe/published_rounds.rs` from the
//! published vectors in `tests/fixtures`; with `--check` it writes nothing and fails when the file
//! differs from what the fixtures give.
//!
//! The self-checks replay every published vector through the library with the round keys the
//! vector records (`src/mhfe/known_answers.rs`), so they need each vector's inputs, container,
//! recovery and the salt and Argon2id key of each of its twelve rounds. This task copies exactly
//! those values; it computes nothing. The output is deterministic: the same fixtures give the same
//! bytes. The unit test `published_round_table_equals_the_fixtures` compares every value with the
//! fixtures again.

use std::fs;
use std::path::Path;

use serde_json::Value;

use crate::{Failure, at};

/// The file the task writes, from the repository's root.
const OUTPUT: &str = "src/mhfe/published_rounds.rs";
/// The folders of `tests/fixtures` with published vectors, and whether each is a same-length
/// suite.
const SUITES: [(&str, bool); 2] = [("suite3-vectors", false), ("suite4-vectors", true)];
/// The vectors of the startup check: every phrase length's packing in either suite, both
/// settings, a non-ASCII password, the repair words and the ambiguous reading. The others run in
/// the full self-test only.
const STARTUP: [&str; 10] = [
    "zero-12",
    "nonzero-15",
    "zero-24",
    "ambiguous-12-21",
    "unicode-password",
    "zero-12-pim-1-memory-level-1",
    "same-length-zero-12",
    "same-length-unicode-password",
    "same-length-zero-18",
    "same-length-nonzero-21",
];
/// Rounds of every MHFE encryption, fixed by the specification.
const ROUNDS: usize = 12;
/// The lines above the table.
const HEADER: &str = "\
//! The published MHFE vectors as the self-checks replay them: inputs, container, recovery and
//! the salt and Argon2id key of every round. Generated by `cargo xtask published-rounds`
//! from tests/fixtures/suite3-vectors and tests/fixtures/suite4-vectors (the specification's
//! vectors/suite3 and vectors/suite4); do not edit. The unit test
//! published_round_table_equals_the_fixtures compares every value with the fixtures.

use super::known_answers::{PublishedReading, PublishedRound, PublishedVector};
use crate::self_check::hex;

";

/// Writes the table, or with `check` refuses a file that differs from it.
pub(crate) fn run(root: &Path, check: bool) -> Result<(), Failure> {
    let text = render(&vectors(root)?)?;
    let output = root.join(OUTPUT);
    if !check {
        return fs::write(&output, text).map_err(|error| at(&output, error));
    }
    if read(&output)? != text {
        return Err(Failure(format!(
            "{OUTPUT} differs from the fixtures; regenerate it"
        )));
    }
    Ok(())
}

/// The text of `path`.
fn read(path: &Path) -> Result<String, Failure> {
    fs::read_to_string(path).map_err(|error| at(path, error))
}

/// Every published vector of both suites, in file-name order within each suite, with whether its
/// suite is a same-length one. The negative cases and the verification records hold no inputs.
fn vectors(root: &Path) -> Result<Vec<(Value, bool)>, Failure> {
    let mut vectors = Vec::new();
    for (folder, same_length) in SUITES {
        let directory = root.join("tests").join("fixtures").join(folder);
        let mut names = Vec::new();
        for entry in fs::read_dir(&directory).map_err(|error| at(&directory, error))? {
            let name = entry.map_err(|error| at(&directory, error))?.file_name();
            if let Some(name) = name.to_str()
                && name.ends_with(".json")
            {
                names.push(name.to_owned());
            }
        }
        names.sort();
        for name in names {
            let path = directory.join(name);
            let vector: Value =
                serde_json::from_str(&read(&path)?).map_err(|error| at(&path, error))?;
            if vector.get("inputs").is_some() {
                vectors.push((vector, same_length));
            }
        }
    }
    Ok(vectors)
}

/// The text of `src/mhfe/published_rounds.rs`.
fn render(published: &[(Value, bool)]) -> Result<String, Failure> {
    let names: Vec<&str> = published
        .iter()
        .filter_map(|(vector, _)| vector["name"].as_str())
        .collect();
    let missing: Vec<&str> = STARTUP
        .into_iter()
        .filter(|name| !names.contains(name))
        .collect();
    if !missing.is_empty() {
        return Err(Failure(format!(
            "startup vectors not found: {}",
            missing.join(", ")
        )));
    }
    let mut lines = vec![format!(
        "pub(super) static PUBLISHED: [PublishedVector; {}] = [",
        published.len()
    )];
    for (vector, same_length) in published {
        push_vector(&mut lines, vector, *same_length)?;
    }
    lines.extend(["];".to_owned(), String::new()]);
    Ok(HEADER.to_owned() + &lines.join("\n"))
}

/// Appends the lines of one vector of the table.
fn push_vector(lines: &mut Vec<String>, vector: &Value, same_length: bool) -> Result<(), Failure> {
    let name = text(vector, "name")?;
    let inputs = &vector["inputs"];
    lines.extend([
        "    PublishedVector {".to_owned(),
        format!("        name: {},", rust_text(name)),
        format!("        same_length: {same_length},"),
        format!("        startup: {},", STARTUP.contains(&name)),
        format!("        phrase: {},", rust_text(text(inputs, "phrase")?)),
        format!(
            "        password: {},",
            rust_text(text(inputs, "password")?)
        ),
        format!(
            "        password_nfkd: {},",
            rust_bytes(text(inputs, "password_nfkd_utf8_hex")?)?
        ),
        format!("        pim: {},", number(inputs, "pim")?),
        format!("        memory_level: {},", number(inputs, "memory_level")?),
        format!(
            "        container: {},",
            rust_text(text(vector, "container")?)
        ),
        "        recovery: &[".to_owned(),
    ]);
    for reading in readings(vector, same_length)? {
        lines.extend([
            "            PublishedReading {".to_owned(),
            format!("                words: {},", number(reading, "words")?),
            format!("                verified: {},", flag(reading, "verified")?),
            format!(
                "                phrase: {},",
                rust_text(text(reading, "phrase")?)
            ),
            "            },".to_owned(),
        ]);
    }
    lines.extend(["        ],".to_owned(), "        rounds: [".to_owned()]);
    let rounds = vector["encryption"]["rounds"]
        .as_array()
        .map_or(&[][..], Vec::as_slice);
    if rounds.len() != ROUNDS {
        return Err(Failure(format!("{name}: {} rounds", rounds.len())));
    }
    for round in rounds {
        lines.extend([
            "            PublishedRound {".to_owned(),
            format!(
                "                salt: hex(\"{}\"),",
                text(round, "salt_hex")?
            ),
            format!(
                "                key: hex(\"{}\"),",
                text(round, "argon2_key_hex")?
            ),
            "            },".to_owned(),
        ]);
    }
    lines.extend(["        ],".to_owned(), "    },".to_owned()]);
    Ok(())
}

/// The readings of a vector's recovery: a list in suite 3, a single reading in suite 4.
fn readings(vector: &Value, same_length: bool) -> Result<Vec<&Value>, Failure> {
    let recovery = &vector["recovery"];
    if same_length {
        return Ok(vec![recovery]);
    }
    let list = recovery
        .as_array()
        .ok_or_else(|| Failure("a published vector's recovery is not a list".to_owned()))?;
    Ok(list.iter().collect())
}

/// The text at `key` of `value`.
fn text<'a>(value: &'a Value, key: &str) -> Result<&'a str, Failure> {
    value[key]
        .as_str()
        .ok_or_else(|| Failure(format!("a published vector's {key} is not text")))
}

/// The whole number at `key` of `value`.
fn number(value: &Value, key: &str) -> Result<u64, Failure> {
    value[key]
        .as_u64()
        .ok_or_else(|| Failure(format!("a published vector's {key} is not a whole number")))
}

/// The flag at `key` of `value`.
fn flag(value: &Value, key: &str) -> Result<bool, Failure> {
    value[key]
        .as_bool()
        .ok_or_else(|| Failure(format!("a published vector's {key} is not a flag")))
}

/// A Rust string literal that keeps the source ASCII: every other character is escaped.
fn rust_text(text: &str) -> String {
    let mut out = String::from('"');
    for character in text.chars() {
        match character {
            '"' | '\\' => {
                out.push('\\');
                out.push(character);
            }
            ' '..='~' => out.push(character),
            _ => out.push_str(&format!("\\u{{{:x}}}", u32::from(character))),
        }
    }
    out.push('"');
    out
}

/// A Rust byte string literal of the bytes `hex` gives, printable ASCII kept.
fn rust_bytes(hex: &str) -> Result<String, Failure> {
    // u8::from_str_radix alone would take a sign, so every character must be a hex digit first.
    if !hex.len().is_multiple_of(2) || !hex.bytes().all(|digit| digit.is_ascii_hexdigit()) {
        return Err(Failure(format!("not hex: {hex}")));
    }
    let mut out = String::from("b\"");
    for at in (0..hex.len()).step_by(2) {
        let byte = hex
            .get(at..at + 2)
            .and_then(|pair| u8::from_str_radix(pair, 16).ok())
            .ok_or_else(|| Failure(format!("not hex: {hex}")))?;
        match byte {
            b'"' | b'\\' => {
                out.push('\\');
                out.push(char::from(byte));
            }
            b' '..=b'~' => out.push(char::from(byte)),
            _ => out.push_str(&format!("\\x{byte:02x}")),
        }
    }
    out.push('"');
    Ok(out)
}
